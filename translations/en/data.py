def present(base, subject):
    third = subject not in {'I', 'You', 'We', 'They', 'The flowers'}
    first, *rest = base.split(' ')
    if first == 'be': first = 'am' if subject == 'I' else ('is' if third else 'are')
    elif third:
        if first == 'have': first = 'has'
        elif first == 'can': pass
        elif first.endswith('y') and first[-2] not in 'aeiou': first = first[:-1] + 'ies'
        elif first.endswith(('s', 'sh', 'ch', 'x', 'z', 'o')): first += 'es'
        else: first += 's'
    return ' '.join([first, *rest])

def sentences():
    result = {}
    for rank, line in enumerate(SENTENCES.splitlines(), 1):
        subject, base, past, part, rest = line.split('|')
        third = subject not in {'I', 'You', 'We', 'They', 'The flowers'}
        end = '?' if subject == 'What' else '.'
        join = lambda verb: ' '.join(x for x in [subject, verb, rest] if x) + end
        result[rank] = {'praesens': join(present(base, subject)), 'praeteritum': join(past),
                        'perfekt': join(('has' if third else 'have') + ' ' + part)}
    assert len(result) == 140
    return result
